#!/usr/bin/env python3
"""Scan a repository and fill rigor-os/project-context templates."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def find_root(start: Path) -> Path:
    p = start.resolve()
    for cand in [p, *p.parents]:
        if (cand / "rigor-os").is_dir():
            return cand
        if (cand / ".git").exists() and (cand / "rigor-os").is_dir():
            return cand
    return p


def detect(root: Path) -> dict:
    info: dict = {
        "backend": [],
        "frontend": [],
        "mobile": [],
        "database": [],
        "docker": False,
        "ci": [],
        "commands": {},
        "profile": "Medium",
    }
    if (root / "manage.py").exists():
        info["backend"].append("Django")
        info["commands"]["migrate"] = "python manage.py migrate"
        info["commands"]["test"] = "pytest"
        info["commands"]["lint"] = "ruff check ."
    if (root / "pyproject.toml").exists() or (root / "requirements.txt").exists():
        if "Django" not in info["backend"]:
            info["backend"].append("Python")
    pkg = root / "package.json"
    if pkg.exists():
        info["frontend"].append("Node")
        try:
            data = json.loads(pkg.read_text(encoding="utf-8"))
            deps = {**data.get("dependencies", {}), **data.get("devDependencies", {})}
            if "next" in deps:
                info["frontend"].append("Next.js")
            if "react" in deps:
                info["frontend"].append("React")
            scripts = data.get("scripts", {})
            if "lint" in scripts:
                info["commands"]["fe_lint"] = "npm run lint"
            if "test" in scripts:
                info["commands"]["fe_test"] = "npm test"
            if "build" in scripts:
                info["commands"]["fe_build"] = "npm run build"
        except json.JSONDecodeError:
            pass
    # Android / mobile
    gradle_files = list(root.glob("**/build.gradle*"))[:20]
    manifests = list(root.glob("**/AndroidManifest.xml"))[:10]
    if gradle_files or manifests:
        info["mobile"].append("Android")
        if any(root.glob("**/*.kt")):
            info["mobile"].append("Kotlin")
        info["commands"].setdefault("android_test", "./gradlew test")
        info["commands"].setdefault("android_assemble", "./gradlew :app:assembleDebug")
        info["commands"].setdefault("android_lint", "./gradlew lint")
    if (root / "ProjectSettings" / "ProjectVersion.txt").exists() or (
        root / "Assets"
    ).is_dir() and list(root.glob("**/*.unity"))[:1]:
        info["mobile"].append("Unity")
    if (root / "project.godot").exists():
        info["mobile"].append("Godot")
    for name in ("docker-compose.yml", "compose.yml", "compose.yaml"):
        if (root / name).exists():
            info["docker"] = True
    if any(root.glob("**/Dockerfile")):
        info["docker"] = True
    if (root / ".github" / "workflows").is_dir():
        info["ci"].append("GitHub Actions")
    # heuristics for DB
    text_blob = ""
    for f in ("requirements.txt", "pyproject.toml", "package.json"):
        fp = root / f
        if fp.exists():
            text_blob += fp.read_text(encoding="utf-8", errors="ignore")
    if "postgres" in text_blob.lower() or "psycopg" in text_blob.lower():
        info["database"].append("PostgreSQL")
    if "redis" in text_blob.lower():
        info["database"].append("Redis")
    return info


def context_dir(root: Path) -> Path:
    """Prefer vendored rigor-os/project-context; else this repo's project-context."""
    nested = root / "rigor-os" / "project-context"
    if nested.is_dir() or (root / "rigor-os").is_dir():
        nested.mkdir(parents=True, exist_ok=True)
        return nested
    if (root / "constitution").is_dir() and (root / "skills").is_dir():
        pc = root / "project-context"
        pc.mkdir(parents=True, exist_ok=True)
        return pc
    nested.mkdir(parents=True, exist_ok=True)
    return nested


def write_context(root: Path, info: dict) -> None:
    pc = context_dir(root)

    project = f"""# Project Context (generated by bootstrap.py)

## Profile

{info["profile"]}

## Product

_Describe the product in one paragraph._

## Stack

- Backend: {", ".join(info["backend"]) or "unknown"}
- Frontend / Web: {", ".join(info["frontend"]) or "unknown"}
- Mobile / Android: {", ".join(info["mobile"]) or "none detected"}
- Database: {", ".join(info["database"]) or "unknown"}
- Cache / queue: {"Redis" if "Redis" in info["database"] else "unknown"}
- Auth: _fill in_
- Docker: {"yes" if info["docker"] else "no"}
- CI: {", ".join(info["ci"]) or "none detected"}
- Model routing: see MODEL_ROUTING.md (T0–T3 → economy/standard/strong/max)
## Repository layout

_Fill module map after first exploration._

## Domain boundaries

_Fill._

## API conventions

Pagination keys: current, page_count, page_size, count, next, previous, results (adjust if different)
Error shape: _match sibling endpoints_
Auth: _fill_

## Critical business rules

_Fill._

## External integrations

_Fill._

## Mobile notes

If Android/game: also fill `MOBILE.md` in this folder (client type, engine, build commands).
"""
    (pc / "PROJECT_CONTEXT.md").write_text(project, encoding="utf-8")

    cmds = ["# Commands (generated — edit to match reality)", ""]
    for k, v in info["commands"].items():
        cmds.append(f"## {k}")
        cmds.append("")
        cmds.append("```")
        cmds.append(v)
        cmds.append("```")
        cmds.append("")
    if info["docker"]:
        cmds.append("## docker")
        cmds.append("")
        cmds.append("```")
        cmds.append(
            "docker compose -f rigor-os/docker/fullstack/compose.yml up --build"
        )
        cmds.append("```")
        cmds.append("")
    (pc / "COMMANDS.md").write_text("\n".join(cmds), encoding="utf-8")

    arch = """# Architecture (generated stub)

## System map

_Fill after reading the codebase._

## Apps / modules

_Fill._

## Data stores

_Fill._

## Background jobs

_Fill._

## Authn / authz model

_Fill._

## Deployment topology

_Fill._

## Mobile clients

_Fill if Android/game — modules, engines, API base URL config._
"""
    (pc / "ARCHITECTURE.md").write_text(arch, encoding="utf-8")

    if info.get("mobile"):
        mobile = f"""# Mobile / Android Context (generated stub)

## Client type

{"Mobile game" if any(x in info["mobile"] for x in ("Unity", "Godot")) else "Android app"} — detected: {", ".join(info["mobile"])}

## Engine / UI toolkit

_Fill: Compose / Views / Unity / Godot_

## Architecture

_Mirror existing — MVVM / MVI / Clean / engine layout_

## Commands

See COMMANDS.md (android_* entries if detected).

## Server-authoritative systems (games)

_score, currency, IAP — fill_
"""
        (pc / "MOBILE.md").write_text(mobile, encoding="utf-8")

    has_stack = bool(info.get("backend") or info.get("frontend") or info.get("mobile"))
    stack_path = pc / "STACK_DECISION.md"
    if not has_stack:
        stack_path.write_text(
            """# Stack Decision

## Status

**No stack detected.** Run skill `stack-selection` / workflow `StackSelection`:
classify project type (web, mobile-game, llm-app, …) and apply
`standards/DefaultStackMatrix.md`. Then fill this file.

## Project type

_pending_

## Chosen stack

_pending_

## Rationale

_pending_
""",
            encoding="utf-8",
        )
    elif not stack_path.exists():
        stack_path.write_text(
            f"""# Stack Decision

## Status

Existing stack detected — **do not re-select**.

- Backend: {", ".join(info.get("backend") or ["—"])}
- Frontend / Web: {", ".join(info.get("frontend") or ["—"])}
- Mobile: {", ".join(info.get("mobile") or ["—"])}

Match sibling patterns. See `skills/architecture/StackSelectionSkill.md`.
""",
            encoding="utf-8",
        )


def main() -> None:
    parser = argparse.ArgumentParser(description="Bootstrap Rigor OS project context")
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args()
    root = find_root(args.root)
    info = detect(root)
    pc = context_dir(root)
    write_context(root, info)
    print(f"Wrote project-context under {pc}")
    print(f"Detected: {json.dumps(info, indent=2)}")
    if not (info.get("backend") or info.get("frontend") or info.get("mobile")):
        print(
            "HINT: No stack detected — use rigor-os stack-selection "
            "(standards/DefaultStackMatrix.md) before scaffolding."
        )


if __name__ == "__main__":
    main()
